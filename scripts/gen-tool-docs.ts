/** Generates docs/TOOLS.md from the live tool catalog (names, schemas, status, bridge ops). Run: pnpm docs:tools */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { zodToJsonSchema } from "zod-to-json-schema";
import { REPO_ROOT } from "../src/config/index.js";
import { defineAllTools } from "../src/mcp/tools/index.js";
import { TOOL_CATALOG } from "../src/mcp/tools/registry.js";

defineAllTools();
const MODULE_TITLES: Record<string, string> = {
  status: "Status", document: "1. Document management", layers: "2. Layer management", text: "3. Text & typography", shapes: "4. Shapes & graphic design",
  images: "5. Image operations", selection: "6. Selection & masking", background: "7. Background & object editing", retouching: "8. Photo retouching",
  color: "9. Color correction", filters: "10. Filters & effects", compositing: "11. Photo compositing", digital_art: "12. Digital art", ai: "13. AI integration",
  automation: "14. Actions & automation", history_inspection: "15. History & inspection", export: "16. Export & delivery",
  design: "17. AI design engine", ui_design: "18. UI design", jobs: "19. Background jobs",
};

function example(schema: Record<string, unknown>): Record<string, unknown> {
  const props = (schema.properties ?? {}) as Record<string, Record<string, unknown>>;
  const req = (schema.required ?? []) as string[];
  const out: Record<string, unknown> = {};
  for (const k of req) {
    const p = props[k]!;
    if (p.enum) out[k] = (p.enum as unknown[])[0];
    else if (p.type === "number" || p.type === "integer") out[k] = (p.minimum as number) > 0 ? p.minimum : 100;
    else if (p.type === "string") out[k] = k.toLowerCase().includes("path") || k === "folder" || k === "output" || k === "input" ? "designs/example.png" : k === "color" || k === "fill" ? "#1A2B3C" : "Example";
    else if (p.type === "boolean") out[k] = true;
    else if (k === "bounds") out[k] = { left: 0, top: 0, right: 200, bottom: 100 };
    else if (p.type === "array") out[k] = [];
    else out[k] = {};
  }
  return out;
}

const byModule = new Map<string, typeof TOOL_CATALOG extends Map<string, infer V> ? V[] : never>();
for (const t of TOOL_CATALOG.values()) (byModule.get(t.module) ?? byModule.set(t.module, []).get(t.module)!).push(t);

const counts = { supported: 0, partial: 0, unsupported: 0, requires_provider: 0 };
for (const t of TOOL_CATALOG.values()) counts[t.status]++;

let md = `# MCP Tools Reference

_Generated by \`pnpm docs:tools\` from the live catalog — do not edit by hand._

**${TOOL_CATALOG.size} tools**: ${counts.supported} supported, ${counts.partial} partial (documented approximation), ${counts.requires_provider} require an external AI provider, ${counts.unsupported} unsupported (return \`UNSUPPORTED_OPERATION\` with an alternative).

## Common output schema

Every tool returns one text content block containing JSON, plus image blocks when it renders a preview:

\`\`\`json
{ "ok": true, "tool": "<name>", "source": "photoshop | mock | server", "data": { "...tool specific..." }, "warnings": ["..."] }
\`\`\`

Errors set \`isError: true\` and return \`{ "ok": false, "tool": "<name>", "error": { "code": "PHOTOSHOP_ERROR", "message": "...", "details": {} } }\`.
Codes: VALIDATION_ERROR, PHOTOSHOP_NOT_CONNECTED, PHOTOSHOP_ERROR, BRIDGE_TIMEOUT, CANCELLED, NO_ACTIVE_DOCUMENT, LAYER_NOT_FOUND, DOCUMENT_NOT_FOUND, PATH_NOT_ALLOWED, FILE_EXISTS, FILE_NOT_FOUND, CONFIRMATION_REQUIRED, UNSUPPORTED_OPERATION, PROVIDER_NOT_CONFIGURED, PROVIDER_ERROR, LIMIT_EXCEEDED, WORKFLOW_FAILED, INTERNAL_ERROR.

**Permissions.** Read-only tools need nothing beyond a reachable Photoshop (COM on Windows, AppleScript on macOS). Write tools need an open document (unless they create one). Tools that touch files need the path inside \`ALLOWED_PATHS\`. Destructive tools need \`confirm: true\`. AI-provider tools need provider credentials and network access (\`openWorldHint\`).

`;
for (const [mod, tools] of byModule) {
  md += `\n## ${MODULE_TITLES[mod] ?? mod}\n`;
  for (const t of tools) {
    const schema = zodToJsonSchema(t.inputSchema, { target: "jsonSchema7", $refStrategy: "none" }) as Record<string, unknown>;
    delete schema.$schema;
    const ann = t.annotations ?? {};
    const kind = ann.readOnlyHint ? "read-only" : ann.destructiveHint ? "destructive (confirm: true)" : ann.openWorldHint ? "external service" : "write";
    md += `\n### \`${t.name}\`\n\n${t.description}\n\n`;
    md += `- **Status:** ${t.status}${t.limitations ? ` — ${t.limitations}` : ""}\n- **Kind:** ${kind}\n`;
    md += `- **Photoshop implementation (JSX bridge ops):** ${t.commands.length ? t.commands.map((c) => `\`${c}\``).join(", ") : "none (server-side)"}\n`;
    md += `\n<details><summary>Input schema</summary>\n\n\`\`\`json\n${JSON.stringify(schema, null, 2)}\n\`\`\`\n</details>\n\nExample: \`${JSON.stringify({ name: t.name, arguments: example(schema) })}\`\n`;
  }
}
writeFileSync(join(REPO_ROOT, "docs", "TOOLS.md"), md);
console.log(`docs/TOOLS.md: ${TOOL_CATALOG.size} tools`);
